"""Writes src/textmap_data.c: Windows-1250 and ISO-8859-2 to Unicode, and
Unicode letters to plain ASCII (diacritics removed), from Python's codecs
and unicodedata.

    python gen_textmap.py ../src/textmap_data.c"""
import sys
import unicodedata

cp1250 = []
for b in range(0x80, 0x100):
    try:
        cp1250.append(ord(bytes([b]).decode('cp1250')))
    except UnicodeDecodeError:
        cp1250.append(0)
latin2 = [ord(bytes([b]).decode('iso8859_2')) for b in range(0xA0, 0x100)]

special = {'ß': 'ss', 'Ł': 'L', 'ł': 'l', 'Đ': 'D', 'đ': 'd', 'Ø': 'O', 'ø': 'o', 'Æ': 'AE', 'æ': 'ae',
           'Œ': 'OE', 'œ': 'oe', '„': '"', '“': '"', '”': '"', '‚': "'", '‘': "'", '’': "'", '«': '"', '»': '"',
           '–': '-', '—': '-', '…': '...', '€': 'EUR', ' ': ' ', '•': '*', '‹': '<', '›': '>', '×': 'x',
           '÷': '/', '°': 'o', '™': 'TM', '©': '(C)', '®': '(R)', '±': '+-', 'µ': 'u', '·': '.', '§': 'S'}
codes = sorted(set(c for c in cp1250 + latin2 if c >= 0x80) | {ord(c) for c in special} |
               set(range(0xC0, 0x180)))
ascii_rows = []
for u in codes:
    ch = chr(u)
    if ch in special:
        a = special[ch]
    else:
        d = unicodedata.normalize('NFKD', ch)
        a = ''.join(c for c in d if ord(c) < 0x80)
    if a and all(32 <= ord(c) < 127 for c in a) and len(a) <= 3:
        ascii_rows.append((u, a))

out = ['/* Generated by tools/gen_textmap.py from Python\'s codecs - do not edit. */',
       '#include "textmap.h"', '',
       '/* Windows-1250 0x80..0xFF -> Unicode (0 = not used) */',
       'const uint16_t tm_cp1250[128] = {']
for i in range(0, 128, 8):
    out.append('    ' + ', '.join(f'0x{x:04X}' for x in cp1250[i:i + 8]) + ',')
out += ['};', '', '/* ISO-8859-2 0xA0..0xFF -> Unicode */', 'const uint16_t tm_latin2[96] = {']
for i in range(0, 96, 8):
    out.append('    ' + ', '.join(f'0x{x:04X}' for x in latin2[i:i + 8]) + ',')
out += ['};', '', '/* Unicode -> plain ASCII, sorted by code */',
        f'const TmAscii tm_ascii[{len(ascii_rows)}] = {{']
for u, a in ascii_rows:
    esc = a.replace('\\', '\\\\').replace('"', '\\"')
    out.append(f'    {{0x{u:04X}, "{esc}"}},')
out += ['};', f'const unsigned tm_ascii_n = {len(ascii_rows)};', '']
open(sys.argv[1], 'w', encoding='ascii', newline='\n').write('\n'.join(out))
print(len(ascii_rows), 'ascii rows')
